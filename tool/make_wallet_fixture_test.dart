// Writes functions/test/fixtures/wallet_cases.json: random books (ledger lines
// and payouts) with the boxes the Dart WalletBook works out. The JavaScript
// copy in functions/src/wallet.js (computeBoxes) must give the same numbers
// (functions/test/unit/wallet.test.js); test/wallet_fixture_test.dart fails when
// the Dart book and this file disagree.
//
//   flutter test tool/make_wallet_fixture_test.dart
import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:flutter_test/flutter_test.dart';
import 'package:transport_app/core/models/ledger_entry.dart';
import 'package:transport_app/core/models/payout.dart';
import 'package:transport_app/core/money/wallet_book.dart';

Map<String, Object?> scenario(Random r, int n) {
  const types = ['trip_earning', 'platform_commission', 'adjustment', 'trip_earning', 'platform_commission', 'mystery'];
  const statuses = ['requested', 'approved', 'paid', 'rejected', 'reversed'];
  int amount() {
    final k = r.nextInt(20);
    if (k == 0) return 0;
    if (k == 1) return 100000000000 + r.nextInt(3) - 1; // around the largest line
    if (k == 2) return 200000000000; // over the largest line
    final v = r.nextInt(r.nextBool() ? 5000000 : 5000) + 1;
    return r.nextInt(4) == 0 ? -v : v;
  }

  final ledger = [for (var i = 0; i < r.nextInt(16); i++) {'type': types[r.nextInt(types.length)], 'amountPaise': amount()}];
  final payouts = [for (var i = 0; i < r.nextInt(7); i++) {'status': statuses[r.nextInt(statuses.length)], 'amountPaise': amount()}];
  final book = WalletBook.fromSources(
    ledger: [for (var i = 0; i < ledger.length; i++) LedgerEntry(id: 'l${n}_$i', driverId: 'd', bookingId: 'b', type: ledger[i]['type']! as String, amountPaise: ledger[i]['amountPaise']! as int)],
    payouts: [for (var i = 0; i < payouts.length; i++) Payout(id: 'p${n}_$i', driverId: 'd', amountPaise: payouts[i]['amountPaise']! as int, status: payouts[i]['status']! as String)],
  ).balance;
  return {
    'ledger': ledger,
    'payouts': payouts,
    'expected': {'available': book.available.paise, 'held': book.held.paise, 'paidOut': book.paidOut.paise},
  };
}

void main() {
  test('write the wallet fixture', () {
    final r = Random(2026);
    final cases = [for (var n = 0; n < 400; n++) scenario(r, n)];
    final out = File('functions/test/fixtures/wallet_cases.json');
    out.parent.createSync(recursive: true);
    out.writeAsStringSync('${const JsonEncoder.withIndent(' ').convert({'note': 'Generated by tool/make_wallet_fixture_test.dart from the Dart WalletBook. Do not edit by hand.', 'cases': cases})}\n');
    // ignore: avoid_print
    print('${cases.length} cases written');
  });
}
