// Z7: lists every screen file under lib/ with its state: ready, flag-gated (names the flags), or hidden when the flag is off.
// Run: node tool/screen_inventory.js [--write]   (--write rewrites docs/SCREEN_INVENTORY.md)
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
function walk(dir, out) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/_(screen|page)\.dart$|_shell(_v2)?\.dart$/.test(e.name)) out.push(p);
  }
  return out;
}

const keyNames = {};
const feat = fs.readFileSync(path.join(root, 'lib/core/features/features.dart'), 'utf8');
for (const m of feat.matchAll(/static const (\w+) = '(\w+)';/g)) keyNames[m[1]] = m[2];

function flagsIn(text) {
  const out = new Set();
  for (const m of text.matchAll(/FeatureKey\.(\w+)/g)) out.add(keyNames[m[1]] || m[1]);
  return [...out].sort();
}

const rows = [];
for (const f of walk(path.join(root, 'lib'), []).sort()) {
  const rel = path.relative(root, f).replace(/\\/g, '/');
  const text = fs.readFileSync(f, 'utf8');
  const flags = flagsIn(text);
  const hiddenWhenOff = /FeatureGate\(/.test(text);
  const area = rel.split('/')[1] === 'core' ? 'core' : rel.split('/')[1];
  const state = flags.length === 0 ? 'ready' : hiddenWhenOff ? 'flag-off: hidden' : 'flag-off: checked in code';
  rows.push({ rel, area, state, flags });
}

const counts = {};
for (const r of rows) counts[r.state] = (counts[r.state] || 0) + 1;
let md = '# Screen inventory (Z7)\n\nGenerated by `node tool/screen_inventory.js --write`. One row per screen file.\n' +
  '- **ready**: no feature flag in the file; the screen works when its backend is live.\n' +
  '- **flag-off: hidden**: the file uses a `FeatureGate`; the entry point disappears while the flag is OFF (the owner switches it on in Admin > Features).\n' +
  '- **flag-off: checked in code**: the file reads a flag itself and shows the old behaviour or a reason when OFF.\n' +
  'A screen file that contains a flag name is listed with the flag; whether *every* control on it is gated is checked by `test/dead_button_guard_test.dart` (no "Coming soon" without a flag reason).\n\n' +
  `Totals: ${rows.length} screen files; ` + Object.entries(counts).map(([k, v]) => `${k}: ${v}`).join(', ') + '.\n\n' +
  '| Area | Screen file | State | Flags |\n|---|---|---|---|\n' +
  rows.map((r) => `| ${r.area} | ${r.rel} | ${r.state} | ${r.flags.join(', ')} |`).join('\n') + '\n';

if (process.argv.includes('--write')) {
  fs.writeFileSync(path.join(root, 'docs/SCREEN_INVENTORY.md'), md);
  console.log(`wrote docs/SCREEN_INVENTORY.md (${rows.length} screens)`);
} else {
  console.log(md.split('\n').slice(8, 12).join('\n'));
}
