// Makes functions/src/cities.js from lib/core/pricing/cities.dart so the server and the app read places the same way.
// Run: node tool/gen_cities_js.js   (test/server_cities_test.dart fails when the two drift apart)
const fs = require('fs');
const src = fs.readFileSync('lib/core/pricing/cities.dart', 'utf8');
const rows = [];
const re = /City\('([^']+)',\s*'([^']+)',\s*(-?[\d.]+),\s*(-?[\d.]+)(?:,\s*\[([^\]]*)\])?\)/g;
let m;
while ((m = re.exec(src))) {
  const aliases = m[5] ? [...m[5].matchAll(/'([^']+)'/g)].map((a) => a[1]) : [];
  rows.push({ name: m[1], state: m[2], lat: Number(m[3]), lng: Number(m[4]), aliases });
}
if (rows.length < 50) throw new Error('too few cities parsed: ' + rows.length);
const out = `'use strict';
// GENERATED by tool/gen_cities_js.js from lib/core/pricing/cities.dart. Do not edit by hand.
// The same offline city table as the app, so the server names a place the way the app does.

const CITIES = ${JSON.stringify(rows, null, 2)};

function norm(s) {
  return String(s).toLowerCase().replace(/[^a-z ]/g, ' ').replace(/\\s+/g, ' ').trim();
}

// The city mentioned in a free-text place ("Andheri, Mumbai"); the longest matching name or alias wins; null if none.
function findCity(text) {
  const t = \` \${norm(text)} \`;
  let best = null;
  let bestLen = 0;
  for (const c of CITIES) {
    for (const n of [c.name, ...c.aliases]) {
      const key = norm(n);
      if (key.length > bestLen && t.includes(\` \${key} \`)) {
        best = c;
        bestLen = key.length;
      }
    }
  }
  return best;
}

module.exports = { CITIES, findCity };
`;
fs.writeFileSync('functions/src/cities.js', out);
console.log('cities: ' + rows.length);
