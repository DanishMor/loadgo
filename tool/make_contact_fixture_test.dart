// Writes functions/test/fixtures/contact_cases.json: what the Dart contact
// filter (lib/core/comm/contact_filter.dart) answers for a large set of texts.
// The JavaScript port in functions/src/contactFilter.js must give the same answers
// (functions/test/unit/contactFilter.test.js), and test/contact_fixture_test.dart
// fails when the Dart filter and this file disagree.
//
//   flutter test tool/make_contact_fixture_test.dart
//
// It is a test only so it can use the Flutter test runner; it builds no app.
import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:transport_app/core/comm/contact_filter.dart';

/// Every single-quoted string literal in a Dart source file (escapes decoded).
Iterable<String> literals(String src) sync* {
  final re = RegExp(r"'((?:[^'\\\n]|\\.)*)'");
  for (final m in re.allMatches(src)) {
    var s = m.group(1)!;
    s = s.replaceAllMapped(RegExp(r'\\u\{([0-9a-fA-F]+)\}'), (x) => String.fromCharCode(int.parse(x.group(1)!, radix: 16)));
    s = s.replaceAllMapped(RegExp(r'\\u([0-9a-fA-F]{4})'), (x) => String.fromCharCode(int.parse(x.group(1)!, radix: 16)));
    s = s.replaceAll(r"\'", "'").replaceAll(r'\$', r'$').replaceAll(r'\n', '\n').replaceAll(r'\\', r'\');
    if (s.trim().length >= 2) yield s;
  }
}

void main() {
  test('write the contact filter fixture', () {
    final texts = <String>{};
    for (final f in ['test/contact_filter_test.dart', 'test/chat_test.dart', 'test/chat_quick_test.dart']) {
      final file = File(f);
      if (file.existsSync()) texts.addAll(literals(file.readAsStringSync()));
    }
    texts.addAll([
      'ok',
      'Load is 12000 kg',
      'Pickup at 10:30, 4:45 pm tak',
      'Date 12/10/2026 and 2026-10-12',
      'call me',
      'Call Me on whatsapp',
      'w h a t s a p p',
      'send ur number',
      'ravi@okaxis',
      'pay outside the app',
      '98765 43210',
      '987 654 3210 ',
      'nau aath saat chhe paanch char teen do ek zero',
      'rate 25,000 weight 12.5',
      'Invoice 4500012345 for 3 trucks',
      'OTP 482913',
      'order id 9876543210123',
      'पहुँच गया, गाड़ी लोड हो रही है',
      'مجھے کال کریں 9876543210',
      List.filled(7000, 'x').join(),
      '${'9' * 5} ${'a' * 3000} ${'8' * 5}',
    ]);
    final recents = <List<String>>[
      const [],
      const ['98765'],
      const ['reached', '98765'],
      const ['8765', '43'],
    ];
    final cases = <Map<String, Object?>>[];
    for (final t in texts) {
      for (final r in recents) {
        // Only keep the recent-variant when it changes something or for the short ones.
        final kind = ContactFilter.check(t, recent: r);
        if (r.isNotEmpty && t.length > 40) continue;
        cases.add({'text': t, 'recent': r, 'kind': kind?.name});
      }
    }
    final out = File('functions/test/fixtures/contact_cases.json');
    out.parent.createSync(recursive: true);
    out.writeAsStringSync('${const JsonEncoder.withIndent(' ').convert({'note': 'Generated by tool/make_contact_fixture_test.dart from the Dart filter. Do not edit by hand.', 'cases': cases})}\n');
    // ignore: avoid_print
    print('${cases.length} cases written');
  });
}
